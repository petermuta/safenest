// Copies the SQL migrations into lib/server/schema.generated.ts so the server can
// create its tables on first use if the platform hasn't applied them.
// Runs automatically before `next build` (see "prebuild" in package.json).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.join(here, '../netlify/database/migrations');
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
const migrations = files.map((name) => ({ name, sql: readFileSync(path.join(dir, name), 'utf8') }));

writeFileSync(
  path.join(here, '../lib/server/schema.generated.ts'),
  `// GENERATED by scripts/embed-schema.mjs from netlify/database/migrations — do not edit.\n` +
    `export const MIGRATIONS: { name: string; sql: string }[] = ${JSON.stringify(migrations, null, 2)};\n`,
);
console.log(`Embedded ${files.length} migration(s): ${files.join(', ')}`);
